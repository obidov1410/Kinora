function readLang() {
  const stored = localStorage.getItem(LANG_KEY);
  return stored === "uzc" ? "uzc" : "uz";
}

export let currentLang = readLang();

export function getLang() {
  return currentLang;
}

export function setLang(lang, { persist = true } = {}) {
  currentLang = lang === "uzc" ? "uzc" : "uz";
  if (persist) localStorage.setItem(LANG_KEY, currentLang);
  applyTranslations();
  window.dispatchEvent(new CustomEvent("kinora:lang", { detail: currentLang }));
}

export function t(key, vars = {}) {
  const dictionary = translations[currentLang] || translations.uz;
  let value = dictionary[key] ?? translations.uz[key] ?? key;
  for (const [name, replacement] of Object.entries(vars)) {
    value = value.replaceAll(`{${name}}`, String(replacement));
  }
  return value;
}

export function localized(entity, field = "title") {
  if (!entity) return "";
  if (currentLang === "uzc" && entity[`${field}_cyrl`]) return entity[`${field}_cyrl`];
  return entity[field] || "";
}

export function genreLabel(key) {
  return t(`genre_${key}`);
}

export function kindLabel(kind) {
  return t(kind === "series" ? "type_series" : "type_movie");
}

export function applyTranslations(root = document) {
  document.documentElement.lang = currentLang === "uzc" ? "uz-Cyrl" : "uz-Latn";
  root.querySelectorAll("[data-i18n]").forEach((node) => {
    node.textContent = t(node.dataset.i18n);
  });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((node) => {
    node.setAttribute("placeholder", t(node.dataset.i18nPlaceholder));
  });
  root.querySelectorAll("[data-i18n-title]").forEach((node) => {
    node.setAttribute("title", t(node.dataset.i18nTitle));
  });
  root.querySelectorAll("[data-i18n-aria]").forEach((node) => {
    node.setAttribute("aria-label", t(node.dataset.i18nAria));
  });
  root.querySelectorAll("[data-lang-select]").forEach((select) => {
    select.value = currentLang;
  });
}

const MONTHS = {
  uz: ["yan", "fev", "mar", "apr", "may", "iyn", "iyl", "avg", "sen", "okt", "noy", "dek"],
  uzc: ["янв", "фев", "мар", "апр", "май", "июн", "июл", "авг", "сен", "окт", "ноя", "дек"],
};

export function formatDate(value, withTime = false) {
  if (!value) return "—";
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return "—";
  const months = MONTHS[currentLang] || MONTHS.uz;
  const base = `${date.getDate()} ${months[date.getMonth()]} ${date.getFullYear()}`;
  if (!withTime) return base;
  const hours = String(date.getHours()).padStart(2, "0");
  const minutes = String(date.getMinutes()).padStart(2, "0");
  return `${base}, ${hours}:${minutes}`;
}

export function formatNumber(value) {
  return new Intl.NumberFormat(currentLang === "uzc" ? "uz-Cyrl-UZ" : "uz-Latn-UZ").format(Number(value) || 0);
}

export function formatPrice(amount, currency = "UZS") {
  return `${formatNumber(amount)} ${currency}`;
}

